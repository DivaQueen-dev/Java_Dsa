import java.util.Arrays;

/**
* Demonstrates basic Java array declaration, initialization, and usage.
* Uses java.util.Arrays to format output.
*/
public class ArraysBasics {
    public static void main(String[] args) {
        // Initialize an array with values
        int[] arr = {5, 2, 9, 1};

        // Print the array elements using Arrays.toString() helper
        System.out.println("Array elements: " + Arrays.toString(arr));
    }
}

